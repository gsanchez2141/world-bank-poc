CREATE SCHEMA IF NOT EXISTS stg;
CREATE TABLE IF NOT EXISTS stg.observation (
    consumer_run_id text NOT NULL,
    change_kind text NOT NULL CHECK (change_kind IN ('close', 'append')),
    snapshot_id bigint NOT NULL,
    country_iso3 text NOT NULL,
    indicator_code text NOT NULL,
    year integer NOT NULL,
    value numeric(38,18),
    api_payload text NOT NULL,
    record_hash text NOT NULL,
    raw_response_key text NOT NULL,
    raw_record_index integer NOT NULL,
    response_sha256 text NOT NULL,
    raw_object_key text NOT NULL,
    source_url text NOT NULL,
    api_page integer NOT NULL,
    raw_ingested_at timestamptz NOT NULL,
    ingestion_id text NOT NULL,
    stage_run_id text NOT NULL,
    stage_ingested_at timestamptz NOT NULL,
    version integer NOT NULL,
    valid_from timestamptz NOT NULL,
    valid_to timestamptz,
    is_current boolean NOT NULL,
    PRIMARY KEY (consumer_run_id, change_kind, country_iso3, indicator_code, year)
);
